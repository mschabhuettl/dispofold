/**
 * Text for a key with placeholders replaced from params. Throws for unknown keys.
 * {name} inserts the value; {name|one|other} inserts the value and the singular or plural noun after it
 * ("{count|Nachtdienst|Nachtdienste}" gives "1 Nachtdienst" or "5 Nachtdienste").
 */
export function t(key, params) {
  if (!Object.hasOwn(TEXTS, key)) throw new Error(`Unknown text key: ${key}`);
  const text = TEXTS[key];
  if (!params) return text;
  return text.replace(PLACEHOLDER, (match, name, one, other) => {
    if (!Object.hasOwn(params, name)) return match;
    const value = String(params[name]);
    if (one === undefined) return value;
    return `${value} ${Number(value.replace(',', '.')) === 1 ? one : other}`;
  });
}

const PLACEHOLDER = /\{(\w+)(?:\|([^|}]*)\|([^}]*))?\}/g;

